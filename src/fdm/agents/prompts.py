def context_block(product_block: str, persona_block: str, grounding: str) -> str:
    return f"""[상품 정의]
{product_block}

[고객 페르소나]
{persona_block}

[검색된 법령·조정사례 근거]
{grounding}
"""


def advocate_user(ctx: str) -> str:
    return ctx + "\n[지시] 이 페르소나에게 이 상품이 적합한 이유를 주장하라."


def persona_first_user(ctx: str, advocate_text: str) -> str:
    return (
        ctx
        + f"\n[상품 담당자의 권유]\n{advocate_text}\n"
        + "\n[지시] 이 권유에 대한 너의 1차 반응을 JSON으로 출력하라."
    )


def skeptic_user(ctx: str, advocate_text: str, persona_text: str) -> str:
    return (
        ctx
        + f"\n[옹호자 주장]\n{advocate_text}\n\n[페르소나 1차 반응]\n{persona_text}\n"
        + "\n[지시] 옹호자 주장을 반박하고 이 페르소나에게 위험한 지점을 지적하라."
    )


def persona_second_user(ctx: str, advocate_text: str, skeptic_text: str, first: str) -> str:
    return (
        ctx
        + f"\n[옹호자 주장]\n{advocate_text}\n\n[너의 1차 반응]\n{first}\n\n[소비자단체 측 반박]\n{skeptic_text}\n"
        + "\n[지시] 반박을 듣고 난 뒤의 최종 반응을 JSON으로 출력하라. 의향이 바뀌었다면 이유를 밝혀라."
    )


def judge_user(ctx: str, transcript: str) -> str:
    return ctx + f"\n[디베이트 전문]\n{transcript}\n\n[지시] 최종 판정 JSON을 출력하라."


def single_shot_user(ctx: str) -> str:
    return ctx + "\n[지시] 적합성 판정 JSON을 출력하라."
