"""3진영 디베이트 프롬프트.

설계 원칙
  1) 모든 발화는 근거 인용 필수 — 약관 조항 ID, 금소법 조문 ID, 페르소나의 소득/부채 수치 중 하나 이상.
  2) 상대의 직전 발화를 반드시 인용해 반박하게 해 순응 편향(sycophancy)을 억제한다.
  3) 페르소나는 양가감정을 허용한다("가입하겠지만 망설임").
  4) 심판은 금소법 6대 판매원칙 프레임으로만 판정하고, 근거 없는 주장은 채택하지 않는다.
"""

from __future__ import annotations

COMMON_RULES = """\
[공통 규칙]
- 너는 금융사 상품기획팀의 사전 검증 시뮬레이션에 참여한다. 실제 고객에게 상품을 추천하는 것이 아니다.
- 모든 주장에는 근거를 대괄호로 인용하라. 인용 가능한 근거는 다음 세 종류뿐이다:
  (a) 상품 약관/설명서 조항 ID — 예: [약관 제5조]
  (b) 법령·감독기준 문서 ID — 예: [FCPA-19]
  (c) 페르소나의 재무 수치 — 예: [월 여유자금 37만원]
- 근거 없는 단정, 일반론("대체로 유리하다"), 상대 의견에 대한 무비판적 동조는 금지된다.
- 한국어로 답하라. 추론 과정을 길게 쓰지 말고 결론과 근거만 제시하라.
"""

